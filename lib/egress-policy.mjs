// lib/egress-policy.mjs — кому компания разрешает отдавать резюме сотрудников.
//
// Форк Timspark. Это единственное место, где граница из lib/egress-guard.mjs
// расширяется. Пустой список означает запрет всего, кроме loopback: локальная
// модель (Ollama, LM Studio, llama.cpp, vLLM на 127.0.0.1) выводом данных за
// пределы машины не является и в списке не нуждается.
//
// Почему модуль, а не config/llm-endpoints.json, как было сначала. Под config/
// в update-system.mjs зарегистрированы только шаблоны *.example.*, а настоящие
// config/profile.yml и config/plugins.yml числятся пользовательскими и помечены
// в .gitignore как «never auto-updated». Политика уровня компании в этот слой
// не укладывается: пользовательский файл правит тот же, кто запускает скрипт,
// а нам нужно обратное — чтобы добавление провайдера проходило ревью. Модуль в
// lib/ решает это буквально: список живёт в коде, меняется через PR и не может
// быть подменён переменной CAREER_OPS_ROOT.
//
// Добавлять хост сюда — значит открыть стороне доступ к персональным данным
// сотрудников. Это решение компании, а не разработчика. Разбор —
// career-ops-audit.md §7.2.
//
// Формат: имя хоста без схемы, порта и пути. Запись покрывает и поддомены,
// но только по границе точки: 'openai.com' разрешает 'api.openai.com' и не
// разрешает 'notopenai.com'.
//
//   export const ALLOW = ['api.openai.com'];

